let currentLang = localStorage.getItem("regulus_lang") || "ja";

function t(key, ...args) {
  const cur = i18n_translations[currentLang];
  const ja  = i18n_translations["ja"];
  // undefined のときだけフォールバック（空文字 "" は有効な翻訳として扱う）
  let text = (cur && key in cur) ? cur[key]
           : (ja  && key in ja)  ? ja[key]
           : key;
  for (let i = 0; i < args.length; i++) {
    text = text.replace(`{${i}}`, args[i]);
  }
  return text;
}

function setLanguage(lang) {
  if (i18n_translations[lang]) {
    document.body.classList.remove(`lang-${currentLang}`);
    currentLang = lang;
    document.body.classList.add(`lang-${currentLang}`);
    localStorage.setItem("regulus_lang", lang);
    if (lang === 'ar') {
      document.body.setAttribute('dir', 'rtl');
    } else {
      document.body.removeAttribute('dir');
    }
    applyTranslations();
  }
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.innerText = t(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key);
  });

  // innerHTML が必要な要素（<strong> タグを含む）の個別処理
  const infoCreatedBy = document.getElementById("infoCreatedBy");
  if (infoCreatedBy) {
    infoCreatedBy.innerHTML = t("info_created_by");
  }

  // セレクトボックスを現在の言語に同期させる
  document.querySelectorAll('.lang-selector').forEach(sel => sel.value = currentLang);

  // Trigger recalculations if visible
  if (typeof calculateError === "function" && document.getElementById("errorMode") && document.getElementById("errorMode").style.display !== "none") {
    calculateError();
  }
  if (typeof handleReverseCalculation === "function" && document.getElementById("correctionMode") && document.getElementById("correctionMode").style.display !== "none") {
    handleReverseCalculation();
  }
  // 電卓が表示中の場合も再描画
  if (typeof TimeCalc !== "undefined") {
    if (typeof TimeCalc.syncEngineUI === "function") TimeCalc.syncEngineUI();
    if (typeof TimeCalc.updateDisplay === "function") TimeCalc.updateDisplay();
    if (typeof TimeCalc.renderHistory === "function") TimeCalc.renderHistory();
  }
  // 結果一覧が表示中の場合も再描画
  if (typeof renderResultList === "function" && document.getElementById("resultListPage") && document.getElementById("resultListPage").style.display !== "none") {
    renderResultList();
  }
}

document.addEventListener("DOMContentLoaded", () => {
  document.body.classList.add(`lang-${currentLang}`);
  applyTranslations();
});





